#!/usr/bin/env python3

"""Export the French game text as a topic file for the LearnLang study app.

Each label in locale/fr/maps/*.asm becomes one French/English study line, with
the English taken from the same label in maps/*.asm. Map names, vocabulary, and
fixes for spellings forced by the font come from locale/fr/vocab.json.

Usage: utils/export_fr_topic.py OUTPUT.json
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOPIC_ID = "pokemon_crystal_origins"
TITLE = "Pokémon Crystal Origins"

LABEL = re.compile(r"^(\w+Text):")
FRAGMENT = re.compile(r'^\s+(text|line|cont|para) "(.*)"')


def parse_text(path):
	"""Map each text label in an .asm file to its list of (command, string) pairs."""
	labels, current = {}, None
	for line in path.read_text(encoding="utf-8").splitlines():
		if m := LABEL.match(line):
			current = labels.setdefault(m.group(1), [])
		elif current is not None and (m := FRAGMENT.match(line)):
			current.append((m.group(1), m.group(2)))
		elif line.strip() == "done":
			current = None
	return labels


def join_text(fragments, colon):
	"""Rebuild one readable line from text box fragments."""
	out = ""
	for command, s in fragments:
		s = s.replace("#", "Poké")
		if out.endswith("-"):
			out = out[:-1] + s
		elif command == "para" and s[0].isupper() and out[-1] not in ".!?…":
			out += colon + s
		elif out:
			out += " " + s
		else:
			out = s
	return out


def clean_french(text, restore):
	for old, new in restore.items():
		text = text.replace(old, new)
	return re.sub(r"\s*([!?;])", r" \1", text)


def export_map(stem, info, restore):
	fr_path = ROOT / "locale" / "fr" / "maps" / f"{stem}.asm"
	fr = parse_text(fr_path)
	en = parse_text(ROOT / "maps" / f"{stem}.asm")
	missing = sorted(set(fr) - set(en))
	if missing:
		sys.exit(f"{fr_path}: no English text for {', '.join(missing)}")
	lines = [{
		"fr": clean_french(join_text(fragments, " : "), restore),
		"en": join_text(en[label], ": "),
		"note": "Sign" if "Sign" in label else "",
		"kind": "line",
	} for label, fragments in fr.items()]
	return {"name": info["name"], "en": info["en"], "items": info["items"] + lines}


def main():
	if len(sys.argv) != 2:
		sys.exit(__doc__.strip())
	vocab = json.loads((ROOT / "locale" / "fr" / "vocab.json").read_text(encoding="utf-8"))
	stems = sorted(p.stem for p in (ROOT / "locale" / "fr" / "maps").glob("*.asm"))
	undefined = [stem for stem in stems if stem not in vocab["maps"]]
	if undefined:
		sys.exit(f"Add these maps to locale/fr/vocab.json: {', '.join(undefined)}")
	topic = {
		"id": TOPIC_ID,
		"title": TITLE,
		"about": "Lines and vocabulary from the French translation of my own ROM hack, generated by "
			"utils/export_fr_topic.py. Spellings are restored where the game font forces a workaround.",
		"names": vocab["names"],
		"worlds": [export_map(stem, vocab["maps"][stem], vocab["restore"]) for stem in stems],
	}
	text = json.dumps(topic, ensure_ascii=False, indent=2) + "\n"
	Path(sys.argv[1]).write_text(text, encoding="utf-8")
	print(f"{sys.argv[1]}: {sum(len(w['items']) for w in topic['worlds'])} items in {len(stems)} map(s)")


if __name__ == "__main__":
	main()
